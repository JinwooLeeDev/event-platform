-- Apply in a transaction after reviewing the target database. No existing table/data alterations.
CREATE TABLE IF NOT EXISTS event_translation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    locale VARCHAR(10) NOT NULL,
    translated_title VARCHAR(1024) NOT NULL,
    translated_summary VARCHAR(4096) NOT NULL,
    translated_description TEXT NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status = 'COMPLETED'),
    translated_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_event_translation_locale UNIQUE(event_id, locale)
);
CREATE TABLE IF NOT EXISTS translation_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    target_locale VARCHAR(10) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    -- Values are controlled by the queue service: PENDING / PROCESSING / COMPLETED / FAILED.
    status VARCHAR(20) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP,
    last_error VARCHAR(40),
    lease_token VARCHAR(36),
    lease_until TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT uq_translation_job_source UNIQUE(event_id, target_locale, source_hash)
);
CREATE INDEX IF NOT EXISTS idx_translation_job_due ON translation_job(status, next_retry_at, id);
CREATE INDEX IF NOT EXISTS idx_translation_job_lease ON translation_job(status, lease_until);
CREATE TABLE IF NOT EXISTS translation_budget (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    minute_start TIMESTAMP NOT NULL,
    minute_count INTEGER NOT NULL,
    day_start TIMESTAMP NOT NULL,
    day_count INTEGER NOT NULL,
    blocked_until TIMESTAMP
);
INSERT INTO translation_budget(id, minute_start, minute_count, day_start, day_count)
SELECT 1, TIMESTAMP '1970-01-01 00:00:00', 0, TIMESTAMP '1970-01-01 00:00:00', 0
WHERE NOT EXISTS (SELECT 1 FROM translation_budget WHERE id = 1);
